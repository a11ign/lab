/**
 * `docs/coverage.md` is GENERATED and DELIBERATELY UNTRACKED (core issue #158, ceo-ruled 2026-09-07), so there
 * is no committed copy to diff a regeneration against. What this checks instead is SHAPE: the generator runs
 * without throwing, the page says what it is, and it produced something rather than nothing.
 *
 * Moved from the core's `coverage-doc.test.ts` (ADR 0045 cut 1), which ran the generator through the core's
 * `packages/lab/` path and read `docs/coverage.md` in the core's tree. This runs the generator from this
 * repository's root and reads the page from a directory of its own: it writes nothing into any checkout.
 * `generate-coverage-doc.test.ts` beside it holds the generator's own controls (the root it reads, the empty file
 * it refuses).
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { LAB_ROOT } from "./lab-sources.ts";

const GENERATOR = join(LAB_ROOT, "scripts/generate-coverage-doc.ts");
/** Fewer criterion rows than this is a generator that produced almost nothing. */
const MIN_CRITERION_ROWS = 10;

/** Regenerated fresh for every test in this file, never read as a leftover from a previous run. */
function regenerate(): string {
  const dir = mkdtempSync(join(tmpdir(), "coverage-doc-"));
  try {
    const out = join(dir, "coverage.md");
    execFileSync(process.execPath, [GENERATOR, `--out=${out}`], { cwd: dir, encoding: "utf8", stdio: "pipe" });
    return readFileSync(out, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

test("the generator runs and marks its output as generated", () => {
  const page = regenerate();
  assert.match(page, /GENERATED by `npm run docs:coverage`/,
    "the page must say it is generated, or somebody will edit the local copy by hand and lose the edit "
    + "on the next run");
});

test("the page states a count, and the count is not zero", () => {
  // The vacuity guard. A generator that silently produced an empty table would pass the test above, since
  // it only checks the page SAYS it is generated, not that it generated anything real.
  const page = regenerate();
  const assessed = /\*\*assessed\*\* \| (\d+) \|/.exec(page);
  assert.ok(assessed && Number(assessed[1]) > 0, "the page claims zero assessed criteria");
  assert.ok(page.split("\n").filter((l) => l.startsWith("| **")).length >= MIN_CRITERION_ROWS,
    "fewer than ten criterion rows: the generator produced almost nothing");
});
