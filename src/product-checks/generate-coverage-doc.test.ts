/**
 * The coverage generator runs from THIS repository's root (ADR 0045 cut 1, row a11ign#5078).
 *
 * It used to count three directories up and read the ownership file through the core's tree, so it worked only
 * inside the core: from the lab's own root both were wrong and nothing said so. These pin what replaced that,
 * each in both directions.
 *
 * Every test runs a COPY of the generator placed in a fixture root's own `scripts/` directory, because the program takes
 * its root from where it is: a test that named the root as an argument could not see the default. The fixture's
 * `node_modules` is a link to the one this repository resolves `@a11ign/*` from.
 *
 *  - POSITIVE: from a fixture root holding a `rule-ownership.json` it writes `docs/coverage.md` there, with the
 *    `GENERATED by` line, a count above zero, and a "decided by" column that comes from THAT file. Restoring the
 *    three-up root turns this red, which is the mutation the row names.
 *  - NEGATIVE: an empty ownership file, and one that declares no subtypes, exit non-zero and write no page.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { LAB_ROOT } from "./lab-sources.ts";

const GENERATOR_AT = "scripts/generate-coverage-doc.ts";
const GENERATOR = join(LAB_ROOT, GENERATOR_AT);

/** The nearest `node_modules` above the lab that holds `@a11ign/judge`: the lab's own after an install, the core's when laid in it. */
function nodeModulesHoldingJudge(): string {
  for (let dir = LAB_ROOT; ; dir = dirname(dir)) {
    const candidate = join(dir, "node_modules");
    if (existsSync(join(candidate, "@a11ign/judge"))) return candidate;
    if (dir === dirname(dir)) throw new Error(`no node_modules holding @a11ign/judge at or above ${LAB_ROOT}`);
  }
}

type Run = { status: number | null; stderr: string; page: string | null };

/** A fixture root holding `ownership` (or no file), the generator copied into its `scripts/`, run from a directory that is neither. */
function generateAt(ownership: string | null): Run {
  const root = mkdtempSync(join(tmpdir(), "generate-coverage-doc-root-"));
  const cwd = mkdtempSync(join(tmpdir(), "generate-coverage-doc-cwd-"));
  try {
    mkdirSync(dirname(join(root, GENERATOR_AT)));
    copyFileSync(GENERATOR, join(root, GENERATOR_AT));
    symlinkSync(nodeModulesHoldingJudge(), join(root, "node_modules"));
    if (ownership !== null) writeFileSync(join(root, "rule-ownership.json"), ownership);
    const run = spawnSync(process.execPath, [join(root, GENERATOR_AT)], { cwd, encoding: "utf8" });
    const written = join(root, "docs/coverage.md");
    return { status: run.status, stderr: run.stderr, page: existsSync(written) ? readFileSync(written, "utf8") : null };
  } finally {
    rmSync(root, { recursive: true, force: true });
    rmSync(cwd, { recursive: true, force: true });
  }
}

const assessedIn = (page: string): number => Number(/\*\*assessed\*\* \| (\d+) \|/.exec(page)?.[1] ?? 0);

test("from a fixture root it writes the page under that root, from that root's ownership file", () => {
  const run = generateAt(JSON.stringify({ subtypes: { "1.1.1:missing-alt": { decidedBy: "rules" } } }));
  assert.equal(run.status, 0, run.stderr);
  assert.ok(run.page !== null, "no page was written under the fixture root");
  assert.match(run.page, /GENERATED by `npm run docs:coverage`/);
  assert.ok(assessedIn(run.page) > 0, "the page claims zero assessed criteria");
  assert.match(run.page, /`missing-alt` rules/, "the decided-by column did not come from the fixture's ownership file");
});

test("this repository's own ownership file produces a page too, and --out names where it goes", () => {
  const own = readFileSync(join(LAB_ROOT, "rule-ownership.json"), "utf8");
  const run = generateAt(own);
  assert.equal(run.status, 0, run.stderr);
  assert.ok(run.page !== null && assessedIn(run.page) > 0, "the real ownership file produced no page, or a page with no assessed criteria");
  const dir = mkdtempSync(join(tmpdir(), "generate-coverage-doc-out-"));
  try {
    const out = join(dir, "elsewhere", "page.md");
    const direct = spawnSync(process.execPath, [GENERATOR, `--out=${out}`], { cwd: dir, encoding: "utf8" });
    assert.equal(direct.status, 0, direct.stderr);
    assert.equal(readFileSync(out, "utf8"), run.page, "the same ownership file produced a different page at --out");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("an empty ownership file stops the generator and writes no page", () => {
  const run = generateAt("");
  assert.notEqual(run.status, 0, "an empty ownership file produced a page");
  assert.match(run.stderr, /cannot read the subtype ownership/);
  assert.equal(run.page, null);
});

test("an ownership file that declares no subtypes stops the generator and writes no page", () => {
  const run = generateAt(JSON.stringify({ subtypes: {} }));
  assert.notEqual(run.status, 0, "an ownership file with no subtypes produced a page");
  assert.match(run.stderr, /declares no subtypes/);
  assert.equal(run.page, null);
});

test("no ownership file at all stops the generator too", () => {
  const run = generateAt(null);
  assert.notEqual(run.status, 0, "a root with no ownership file produced a page");
  assert.equal(run.page, null);
});

test("the generator names no path into the core's tree and counts no directories above itself", () => {
  const source = readFileSync(GENERATOR, "utf8");
  assert.ok(source.length > 0, "the generator was read as empty");
  assert.doesNotMatch(source, /packages\/lab/, "the generator names the core's `packages/lab` path again");
  assert.doesNotMatch(source, /\.\.\/\.\.\/\.\./, "the generator counts three directories up again");
});
